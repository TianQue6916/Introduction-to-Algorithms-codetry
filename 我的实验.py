def plus (x, y):
    return x + y

def minus(x, y):
    return x - y

def multiply(x, y):
    return x * y

def divide(x, y):
    return x / y

def power(x, y):
    return x ** y

def mod(x, y):
    return x % y

def floor_divide(x, y):
    return x // y

def absolute(x):
    return abs(x)

def round(x):
    return round(x)

def square(x):
    return x ** 2

def cube(x):
    return x ** 3