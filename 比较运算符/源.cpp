#include <iostream>
using namespace std;
//1真0假
int main() {
	//==
	int a = 10, b = 20;

	cout << (a == b) << endl;//括号是为了优先级！！！


	//!=
	
	cout << (a != b) << endl;
	//>
	cout << (a > b) << endl;
	//<
	cout << (a < b) << endl;
	//>=
	cout << (a >= b) << endl;

	//<=

	cout << (a <= b) << endl;

	system("pause");
	return 0;
}